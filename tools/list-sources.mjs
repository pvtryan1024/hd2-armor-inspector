// Writes models/SOURCES.md and models/sources.csv: which game units every 3D model was built from, so others
// can find the same files in Filediver. Reads the source lists in tools/prep-model.mjs (the body unit, and the
// gear hung on its bones) and the archive IDs matched to each enemy in data/data.js.
// Usage: node tools/list-sources.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { SOURCES, LOADOUT } from './prep-model.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'data/data.js'), 'utf8'), ctx);
const DATA = ctx.window.HD2_DATA;
const enemyOf = new Map(DATA.enemies.map((e) => [e.id, e]));

// "extra/0x08886d27a6f6db8c.unit.glb" → unit hash 0x08886d27a6f6db8c; "content/…/x.unit.glb" → that path
const unitOf = (src) => {
  const f = String(src || '');
  const hash = /0x[0-9a-f]{16}/i.exec(f)?.[0];
  if (hash) return { hash: hash.toLowerCase(), path: '' };
  return { hash: '', path: f.replace(/^extra\//, '').replace(/\.unit\.glb$/, '') };
};
const unitText = (u) => (u.hash ? `\`${u.hash}\`` : `\`${u.path}\``);

const rows = [];
for (const [id, cfg] of Object.entries(SOURCES)) {
  const e = enemyOf.get(id);
  const body = cfg.origin ? { hash: '', path: cfg.origin } : unitOf(cfg.src); // origin: where a renamed copy came from
  const gear = (LOADOUT[id] || []).map((g) => ({ ...unitOf(g.src), bone: g.bone || '', name: g.name || '', part: g.part || '' }));
  const archives = (e?.archives || []).map((a) => `${a.id}${a.note ? ` (${a.note})` : ''}${a.exact ? '' : ' [family]'}`);
  rows.push({ id, name: e?.name || id, faction: e?.faction || '', model: fs.existsSync(path.join(root, 'models', `${id}.glb`)) ? `models/${id}.glb` : '', body, gear, archives });
}
const order = ['Terminids', 'Automatons', 'Illuminate'];
rows.sort((a, b) => (order.indexOf(a.faction) + 1 || 9) - (order.indexOf(b.faction) + 1 || 9) || a.name.localeCompare(b.name));

// ---- markdown ----
const md = [
  '# Model sources',
  '',
  'Where each 3D model on the site came from, so the same files can be found in [Filediver](https://github.com/xypwn/filediver).',
  'Generated by `node tools/list-sources.mjs` from the source lists in `tools/prep-model.mjs`; do not edit by hand.',
  '',
  '- **Body unit**: the unit file the enemy was exported from: a `content/…` path in a full Filediver export, or a',
  '  `0x…` unit hash for units without a name (exported on their own, e.g. with `--model-include-lods`).',
  '- **Gear**: units attached to the body\'s bones (guns, launchers, packs): unit → bone, and the hitzone it counts as.',
  '- **Archive IDs**: from the HD2 modding community\'s ID sheet (`data/archive-ids.csv`); [family] = the archive of',
  '  the enemy family (e.g. Hulk) rather than this exact unit.',
  '',
];
for (const fac of [...new Set(rows.map((r) => r.faction))]) {
  md.push(`## ${fac || 'Other'}`, '', '| Enemy | Model | Body unit | Gear (unit → bone: hitzone) | Archive IDs |', '|---|---|---|---|---|');
  for (const r of rows.filter((x) => x.faction === fac)) {
    const gear = r.gear.map((g) => `${unitText(g)} → \`${g.bone}\`${g.part ? `: ${g.part}` : ''}`).join('<br>');
    md.push(`| ${r.name} | ${r.model ? `\`${r.model}\`` : '—'} | ${unitText(r.body)} | ${gear || '—'} | ${r.archives.join('<br>') || '—'} |`);
  }
  md.push('');
}
fs.writeFileSync(path.join(root, 'models/SOURCES.md'), md.join('\n'));

// ---- csv (one row per unit) ----
const esc = (s) => (/[",\n]/.test(s) ? `"${String(s).replace(/"/g, '""')}"` : String(s));
const csv = [['enemy_id', 'enemy', 'faction', 'model', 'role', 'unit_hash', 'unit_path', 'bone', 'hitzone', 'archive_ids'].join(',')];
for (const r of rows) {
  csv.push([r.id, r.name, r.faction, r.model, 'body', r.body.hash, r.body.path, '', '', r.archives.join('; ')].map(esc).join(','));
  for (const g of r.gear) csv.push([r.id, r.name, r.faction, r.model, 'gear', g.hash, g.path, g.bone, g.part, ''].map(esc).join(','));
}
fs.writeFileSync(path.join(root, 'models/sources.csv'), csv.join('\n') + '\n');
console.log(`models/SOURCES.md and models/sources.csv: ${rows.length} enemies, ${rows.reduce((n, r) => n + r.gear.length, 0)} gear units`);
